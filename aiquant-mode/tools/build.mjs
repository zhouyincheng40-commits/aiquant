#!/usr/bin/env node
/**
 * dsh-aiquant-mode 打包脚本：把 presets/aiquant/ 合成 cordis.patch.yml 的预设声明区。
 *
 * 为什么需要它：
 *   DSH 0.1.7+ 的 agent preset **只认 `@deepseek-ai/dsh-agent-preset` 声明行**——
 *   注册表既不扫目录，也不接受预设路径。所以「模式能不能在新会话里被选中」
 *   完全取决于 cordis.patch.yml 里那段 config.plugins。手写两份必然漂移，这里生成。
 *
 * 用法：
 *   node tools/build.mjs           # 重新生成 cordis.patch.yml
 *   node tools/build.mjs --check   # 只校验生成结果与盘上一致（CI/自检用）
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const PRESET_DIR = join(root, 'presets', 'aiquant')
const HEAD = join(root, 'tools', 'patch-head.yml')
const OUT = join(root, 'cordis.patch.yml')

const BEGIN = '# >>> preset-aiquant declaration (generated by tools/build.mjs) >>>'
const END = '# <<< preset-aiquant declaration <<<'

/** 从 preset.yml 里取一个标量字段（只支持单行 name/description，够用且不引 YAML 依赖）。 */
function presetField(text, key) {
  const match = new RegExp('^' + key + ':\\s*(.*)$', 'm').exec(text)
  if (match === null) throw new Error('presets/aiquant/preset.yml 缺少字段：' + key)
  const raw = match[1].trim()
  // 用 JSON 转义成双引号 YAML 标量：中文、引号、换行都安全
  return JSON.stringify(raw.replace(/^"|"$/g, ''))
}

/** 把 plugins 列表整体缩进到 config.plugins: 下面。 */
function indent(text, spaces) {
  const pad = ' '.repeat(spaces)
  return text
    .replace(/\r\n/g, '\n')
    .replace(/\s+$/, '')
    .split('\n')
    .map((line) => (line.trim() === '' ? '' : pad + line))
    .join('\n')
}

const presetMeta = readFileSync(join(PRESET_DIR, 'preset.yml'), 'utf8')
const agentYml = readFileSync(join(PRESET_DIR, 'agent.cordis.yml'), 'utf8')
const name = presetField(presetMeta, 'name')
const description = presetField(presetMeta, 'description')

const generated = [
  BEGIN,
  '- insert:',
  '    - id: preset-aiquant',
  "      name: '@deepseek-ai/dsh-agent-preset'",
  '      config:',
  '        id: aiquant',
  '        name: ' + name,
  '        description: ' + description,
  '        order: 20',
  '        plugins:',
  indent(agentYml, 10),
  END,
].join('\n')

const head = readFileSync(HEAD, 'utf8').replace(/\s+$/, '')
const output = [
  '# dsh-aiquant-mode bundle patch（由 tools/build.mjs 生成，勿手改生成区）',
  '#',
  '# 生成的预设声明来源：presets/aiquant/preset.yml + presets/aiquant/agent.cordis.yml',
  '# 重新生成：node tools/build.mjs',
  '',
  head,
  '',
  '# 1) 模式声明：新会话里能否选到「AI量化模式」由这一段决定。',
  '#    声明行里不要写死绝对路径；技能目录用运行时表达式解析（见 agent.cordis.yml）。',
  generated,
  '',
].join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try { current = readFileSync(OUT, 'utf8') } catch { current = '' }
  if (current !== output) {
    console.error('cordis.patch.yml 与 presets/ 不一致：请跑 node tools/build.mjs')
    process.exit(1)
  }
  console.log('OK: cordis.patch.yml 与 presets/ 一致（' + output.length + ' 字节）')
} else {
  writeFileSync(OUT, output, 'utf8')
  console.log('已生成 ' + OUT + '（' + output.length + ' 字节，预设 id=aiquant，' + name + '）')
}
